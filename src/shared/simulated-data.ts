function buildSimulatedHistory(
  points: Array<{
    daysAgo: number;
    priceMxn: number;
    listPriceMxn: number;
    effectiveAvailability: PriceHistoryPoint['effectiveAvailability'];
    buttonState: PriceHistoryPoint['buttonState'];
    eventTag?: PriceHistoryPoint['eventTag'];
    eventNote?: string;
  }>
): PriceHistoryPoint[] {
  const baseDate = new Date('2026-11-19T12:00:00-06:00');
  return points.map((p) => {
    const d = new Date(baseDate);
    d.setDate(d.getDate() - p.daysAgo);
    const yyyy = d.getFullYear();
    const mm = String(d.getMonth() + 1).padStart(2, '0');
    const dd = String(d.getDate()).padStart(2, '0');
    return {
      date: `${yyyy}-${mm}-${dd}`,
      priceMxn: p.priceMxn,
      listPriceMxn: p.listPriceMxn,
      effectiveAvailability: p.effectiveAvailability,
      buttonState: p.buttonState,
      eventTag: p.eventTag,
      eventNote: p.eventNote,
    };
  });
}

